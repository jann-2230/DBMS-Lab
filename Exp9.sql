Aim

To study the different types of NoSQL databases.

Types of NoSQL Databases

1. Key-Value Pair-Based Database

A key-value database stores data as a collection of key-value pairs. Each key is unique and is used to access its corresponding value.

Example: Redis, Amazon DynamoDB.

2. Column-Based Database

A column-based database stores data in columns instead of rows. It is suitable for handling large amounts of data and provides efficient data access.

Example: Apache Cassandra, HBase.

3. Document-Oriented Database

A document-oriented database stores data as documents, usually in formats such as JSON or BSON. Each document can contain different fields and values.

Example: MongoDB, CouchDB.

4. Graph-Based Database

A graph-based database stores data using nodes and relationships (edges). It is useful for representing and analyzing relationships between data items.

Example: Neo4j, Amazon Neptune.

Result

Thus, the different types of NoSQL databases, namely Key-Value Pair-Based, Column-Based, Document-Oriented, and Graph-Based databases, were studied.
